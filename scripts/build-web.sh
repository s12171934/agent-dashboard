#!/bin/sh
# Build the Rust CSR app and matching wasm-bindgen glue into an immutable asset directory.
set -eu
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"
VERSION=0.2.130
CARGO="$ROOT/server/cargo"
if command -v rustup >/dev/null 2>&1; then rustup target add wasm32-unknown-unknown
else RUSTUP_HOME="$ROOT/.tools/rustup" CARGO_HOME="$ROOT/.tools/cargo" "$ROOT/.tools/cargo/bin/rustup" target add wasm32-unknown-unknown; fi
BINDGEN="${WASM_BINDGEN:-$ROOT/.tools/wasm-bindgen/bin/wasm-bindgen}"
if [ ! -x "$BINDGEN" ] || [ "$("$BINDGEN" --version)" != "wasm-bindgen $VERSION" ]; then
  "$CARGO" install wasm-bindgen-cli --version "$VERSION" --locked --root "$ROOT/.tools/wasm-bindgen"
  BINDGEN="$ROOT/.tools/wasm-bindgen/bin/wasm-bindgen"
fi
"$CARGO" build --locked --manifest-path "$ROOT/web-ui/Cargo.toml" --target wasm32-unknown-unknown --release
OUT="$(mktemp -d)"
trap 'rm -rf "$OUT"' EXIT
"$BINDGEN" --target web --no-typescript --remove-name-section --remove-producers-section --out-dir "$OUT" --out-name app "$ROOT/web-ui/target/wasm32-unknown-unknown/release/agent_dashboard_ui.wasm"
python3 - "$ROOT" "$OUT" <<'PY'
import sys,pathlib,hashlib,shutil,json
root,out=map(pathlib.Path,sys.argv[1:]); files=sorted(p for p in out.rglob('*') if p.is_file()); h=hashlib.sha256()
for p in files:h.update(p.relative_to(out).as_posix().encode());h.update(p.read_bytes())
version=h.hexdigest()[:16]; dest=root/'frontend/wasm'/version
dest.parent.mkdir(exist_ok=True)
if not dest.exists():shutil.copytree(out,dest)
manifest={'version':version,'files':[f'wasm/{version}/{p.relative_to(out).as_posix()}' for p in files]}
(root/'frontend/wasm/manifest.json').write_text(json.dumps(manifest)+'\n')
(root/'frontend/rust-ui.js').write_text(f'''// Generated by scripts/build-web.sh. JS and WASM share an immutable version.
import init from './wasm/{version}/app.js';
try {{ await init(); document.getElementById('wasm-loading')?.remove(); }}
catch (error) {{ console.error(error); const box=document.getElementById('wasm-loading'); if(box){{box.textContent='화면을 불러오지 못했습니다. 연결을 확인한 뒤 앱을 새로 고침하세요.';box.setAttribute('role','alert');}} }}
''')
print(f'Rust/WASM UI {version}: {sum(p.stat().st_size for p in files):,} bytes')
PY
